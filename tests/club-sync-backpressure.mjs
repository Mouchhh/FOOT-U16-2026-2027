import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('club-network.js','utf8');
const queue=source.slice(source.indexOf('function clubNetworkQueueSync(){'),source.indexOf('async function clubNetworkSync(){'));
let calls=0,release;
const ctx=vm.createContext({Date,Promise,clubNetworkQueue:null,clubNetworkRetryAfter:0,clubNetworkSync:()=>{calls++;return new Promise(r=>release=r);}});
vm.runInContext(queue,ctx);
const first=ctx.clubNetworkQueueSync();
for(let i=0;i<100;i++)assert.equal(ctx.clubNetworkQueueSync(),first);
await Promise.resolve();assert.equal(calls,1);release();await first;
await Promise.resolve();assert.equal(calls,1,'No backlog after a burst of events');
ctx.clubNetworkRetryAfter=Date.now()+30000;await ctx.clubNetworkQueueSync();assert.equal(calls,1);
ctx.clubNetworkRetryAfter=0;ctx.clubNetworkSync=()=>{calls++;return Promise.reject(new Error('offline'));};
await assert.rejects(ctx.clubNetworkQueueSync(),/offline/);assert.equal(ctx.clubNetworkQueue,null);
ctx.clubNetworkSync=()=>{calls++;return Promise.resolve();};await ctx.clubNetworkQueueSync();assert.equal(calls,3);
console.log('PASS sync coalescing, cooldown, failure cleanup and later retry');
